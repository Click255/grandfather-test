# 门禁校验
if not st.session_state.auth:
    st.title("👴 测测你前世有没有殴打过大爷")
    st.write("---")
    st.markdown("##### 🔑 请输入您的专属密语入场")
    st.caption("密语格式：小红书订单号后4位 + 大爷 (例如：1234大爷)")
    
    pw = st.text_input("请输入密语", type="default", placeholder="1234大爷")
    
    if st.button("开启轮回"):
        if "大爷" in pw and len(pw) >= 6:
            current_uses = global_tracker.get(pw, 0)
            # 修改点1：允许前三次进入
            if current_uses < 3:
                st.session_state.auth = True
                st.session_state.current_key = pw
                st.rerun()
            else:
                st.error("⚠️ 此密语的因果已耗尽（限3次）。如有疑问请私信主理人。")
        else:
            st.error("密语格式错误。请输入：订单后四位 + 大爷")
    st.stop()

# 检查当前密语是否在答题过程中耗尽
current_total_uses = global_tracker.get(st.session_state.current_key, 0)

# 修改点2：改为大于 3 才拦截，确保第 3 次测试能走完最后一步并显示结果
if current_total_uses > 3:
    st.error(f"⚠️ 密语 [{st.session_state.current_key}] 的因果已耗尽。")
    if st.button("退出"):
        st.session_state.auth = False
        st.rerun()
else:
    # 答题逻辑
    idx = st.session_state.step
    if idx < len(QS):
        st.progress((idx + 1) / len(QS))
        st.subheader(f"第 {idx + 1} / {len(QS)} 题")
        
        q_text, raw_opts = QS[idx]
        opts = sorted(raw_opts, key=lambda x: x[0]) 
        
        choice = st.radio(q_text, [o[0] for o in opts], key=f"q_{idx}")
        
        col1, col2 = st.columns(2)
        with col1:
            if idx > 0 and st.button("⬅️ 上一题"):
                st.session_state.step -= 1
                st.rerun()
        with col2:
            button_label = "下一题 ➡️" if idx < len(QS)-1 else "🏮 查看裁决"
            if st.button(button_label):
                for text, val in opts:
                    if choice == text: st.session_state.ans[idx] = val
                
                if idx < len(QS)-1:
                    st.session_state.step += 1
                else:
                    # 只有在这里点击查看裁决，才正式消耗一次因果
                    global_tracker[st.session_state.current_key] = global_tracker.get(st.session_state.current_key, 0) + 1
                    st.session_state.step = 999 
                st.rerun()

    # 结果显示逻辑
    else:
        st.balloons()
        total = sum(st.session_state.ans.values())
        st.subheader("因果裁决书如下：")
        
